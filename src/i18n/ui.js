/** Current page language, read from <html lang>. Falls back to Italian. */
export function currentLang() {
  if (typeof document === 'undefined') return 'it';
  const lang = (document.documentElement.getAttribute('lang') || 'it').slice(0, 2).toLowerCase();
  return lang === 'en' ? 'en' : 'it';
}

/**
 * Looks up a string for the current language and fills {placeholders}.
 * Unknown keys come back as the key itself, which makes them obvious in the UI.
 */
export function t(key, vars) {
  const lang = currentLang();
  const value = STRINGS[lang]?.[key] ?? STRINGS.it[key] ?? key;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  );
}

